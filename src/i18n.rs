#[test]
fn fill_and_pick() {
    assert_eq!(fill(EN.save_some, &[("n", &2), ("all", &5)]), "Save 2 of 5 pages");
    assert_eq!(fill("{a}{a}", &[("a", &"x")]), "xx");
    // (not through set: other tests draw the screen in the language they started with)
    assert_eq!(ALL[find("pt_BR.UTF-8").unwrap()].code, "pt");
    assert_eq!(find("C"), None);
}

#[test]
fn every_language_fits_the_form() {
    for t in ALL {
        // the printer's name and the hints are filled in, not translated
        assert!(fill(t.at_service, &[("name", &"X")]).contains('X'), "{}", t.code);
        // labels short enough to leave room for the values next to them
        for label in t.labels.iter().chain(&t.scan_labels) {
            assert!(unicode_width::UnicodeWidthStr::width(*label) <= 16, "{}: {label}", t.code);
        }
    }
}
